export const dictionaries: Record<Locale, Dictionary> = { en, km, zh };

export const locales: { code: Locale; label: string }[] = [
  { code: "en", label: "EN" },
  { code: "km", label: "ខ្មែរ" },
  { code: "zh", label: "中文" },
];

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Dictionary;
};

const I18nContext = createContext<I18nValue>({
  locale: "en",
  setLocale: () => {},
  t: dictionaries.en,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    setLocaleState("en");
    setReady(true);
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    if (!ready) return;
    const root = document.documentElement;
    root.lang = locale === "zh" ? "zh-CN" : locale;
    root.dataset.locale = locale;
  }, [locale, ready]);

  const value = useMemo<I18nValue>(
    () => ({ locale, setLocale, t: dictionaries[locale] }),
    [locale, setLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className="flex items-center gap-1" role="group" aria-label={t.lang.label}>
      {locales.map((item) => (
        <button
          key={item.code}
          type="button"
          onClick={() => setLocale(item.code)}
          className={`rounded-full px-2.5 py-1.5 text-xs ${
            locale === item.code
              ? "bg-primary text-primary-foreground"
              : "text-muted-foreground hover:bg-muted"
          } ${item.code === "km" ? "kh" : item.code === "zh" ? "zh" : ""}`}
          aria-pressed={locale === item.code}
        >
          {item.label}
        </button>
      ))}
    </div>
  );
}
